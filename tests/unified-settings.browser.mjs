import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import net from 'node:net';
import { spawn } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright';

const app = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const temporary = await fs.realpath(await fs.mkdtemp(path.join(os.tmpdir(), 'prota-settings-e2e-')));
const source = path.join(temporary, 'source');
const target = path.join(temporary, '工作区');
const config = path.join(temporary, 'config');
const children = [];
let browser;
const write = async (relative, content) => { const file = path.join(source, relative); await fs.mkdir(path.dirname(file), { recursive: true }); await fs.writeFile(file, content); };
const freePort = () => new Promise(resolve => { const server = net.createServer().listen(0, '127.0.0.1', () => { const port = server.address().port; server.close(() => resolve(port)); }); });
const wait = async (predicate, label) => { for (let index = 0; index < 150; index++) { try { if (await predicate()) return; } catch {} await new Promise(resolve => setTimeout(resolve, 100)); } throw Error(`Timed out: ${label}`); };

try {
    await write('workspace.json', JSON.stringify({ id: 'source-test-workspace', formatVersion: 1 }));
    await write('data/projects.json', JSON.stringify({ projects: [{ id: 'workspace-e2e', name: '设置验证工作区', pages: [{ id: 'reader', name: '测试页面', versions: ['v1'], activeVersion: 'v1', targetDevice: 'mobile' }] }], activeProjectId: 'workspace-e2e', activePageId: 'reader' }));
    await write('src/pages/workspace-e2e/reader/v1/index.html', '<!doctype html><html lang="zh"><head><link rel="stylesheet" href="styles.css"></head><body><h1>迁移验证</h1><script src="app.js"></script></body></html>');
    await write('src/pages/workspace-e2e/reader/v1/styles.css', 'body { color: #333 }');
    await write('src/pages/workspace-e2e/reader/v1/app.js', 'console.log("workspace asset")');
    await write('src/pages/workspace-e2e/reader/v1/annotations.json', '[{"text":"保留标注"}]');
    await write('src/pages/workspace-e2e/reader/docs/product.md', '# 产品文档\n迁移后保持可读');
    const historySummary = { id: 'retained-history', title: '保留会话', sessionScope: 'page', projectId: 'workspace-e2e', pageId: 'reader', version: 'v1', status: 'succeeded', hasHistory: true, createdAt: '2026-10-21T00:00:00Z', updatedAt: '2026-10-21T00:00:00Z' };
    await write('data/agent-sessions/index.json', JSON.stringify({ sessions: [historySummary] }));
    await write('data/agent-sessions/retained-history.json', JSON.stringify({ ...historySummary, context: { projectId: 'workspace-e2e', pageId: 'reader', version: 'v1' }, providerSummary: {}, timeline: [{ type: 'message', payload: { text: '保留历史' } }], runState: { active: false, status: 'succeeded' } }));
    await fs.mkdir(config);
    await fs.writeFile(path.join(config, 'workspace.json'), JSON.stringify({ path: source }));
    await fs.writeFile(path.join(config, 'agent-provider-config.json'), JSON.stringify({ providers: [{ id: 'fixture-provider', label: '测试模型', model: 'fixture-model', apiKey: 'fixture-only-key', baseURL: 'https://example.invalid/v1', apiType: 'openai-completions', sdkOptions: {} }], activeProviderId: 'fixture-provider', selectedProviderId: 'fixture-provider' }));
    const bridgePort = await freePort(), agentPort = await freePort();
    const base = `http://127.0.0.1:${bridgePort}`;
    const env = { ...process.env, PYTHONDONTWRITEBYTECODE: '1', READIFY_CONFIG_DIR: config, READIFY_PORT: String(bridgePort), READIFY_AGENT_PORT: String(agentPort) };
    delete env.READIFY_WORKSPACE;
    let logs = '';
    for (const [command, args] of [['python3', ['server/bridge.py']], ['node', ['server/agent-server.mjs']]]) {
        const child = spawn(command, args, { cwd: app, env, stdio: ['ignore', 'pipe', 'pipe'] });
        child.stdout.on('data', chunk => logs += chunk); child.stderr.on('data', chunk => logs += chunk); children.push(child);
    }
    await wait(async () => (await fetch(`${base}/api/workspace`)).ok, 'bridge startup');
    await wait(async () => (await fetch(`http://127.0.0.1:${agentPort}/api/agent/health`)).ok, 'agent startup');
    const originalShell = await fs.readFile(path.join(app, 'portal/shell.js'), 'utf8');
    browser = await chromium.launch({ headless: true });
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
    page.setDefaultTimeout(15000);
    const pageErrors = [];
    page.on('pageerror', error => pageErrors.push(error.message));
    await page.route(/fonts\.google/, route => route.abort());
    await page.route(/http:\/\/(localhost|127\.0\.0\.1):8081\//, route => route.continue({ url: route.request().url().replace(/:8081\//, `:${agentPort}/`) }));
    await page.goto(`${base}/portal/index.html`, { waitUntil: 'domcontentloaded' });
    await page.locator('#globalSettingsBtn').click();
    assert.equal((await page.locator('#globalSettingsBtn').textContent()).trim(), '');
    assert.equal(await page.locator('#globalSettingsBtn').getAttribute('aria-label'), '设置');
    assert.equal(await page.locator('#globalSettingsBtn svg').count(), 1);
    assert.equal(await page.locator('.us-sidebar nav button svg').count(), 3);
    await page.locator('#usCurrentPath').filter({ hasText: source }).waitFor();
    assert.equal(await page.locator('.unified-settings [role=dialog]').count(), 1);
    await page.locator('[data-us-tab=sharing]').click();
    await page.locator('#staticDomainInput').fill('fixture.example.com');
    await page.locator('[data-us-tab=models]').click();
    assert.equal(await page.locator('#agentConfigModal').isVisible(), true);
    await page.locator('[data-us-tab=sharing]').click();
    assert.equal(await page.locator('#staticDomainInput').inputValue(), 'fixture.example.com');
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('#usGuard').isVisible(), true);
    await page.locator('[data-us-save-continue]').click();
    await page.locator('.unified-settings').waitFor({ state: 'hidden' });
    assert.equal((await fs.readFile(path.join(source, 'data/settings.json'), 'utf8')).includes('fixture.example.com'), true);
    await page.locator('#globalSettingsBtn').click();
    await page.locator('[data-us-tab=models]').click();
    await page.locator('.provider-advanced summary').click();
    await page.locator('#agentProviderNameInput').fill('已修改的测试模型');
    await page.locator('#agentSaveProviderBtn').click();
    await wait(async () => !await page.locator('[data-us-tab=models]').evaluate(node => node.classList.contains('is-dirty')), 'model save');
    assert.equal(JSON.parse(await fs.readFile(path.join(config, 'agent-provider-config.json'), 'utf8')).providers[0].label, '已修改的测试模型');
    // Discovery changes only the draft, and model-list-only edits are guarded.
    await page.route('**/api/agent/fetch-models', route => route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ ok: true, models: ['fixture-new-model', 'fixture-second-model'] }) }));
    await page.locator('#agentFetchModelsBtn').click();
    await page.locator('#agentModelInput option[value="fixture-new-model"]').waitFor({state:'attached'});
    assert.equal(await page.locator('#agentModelInput').inputValue(), 'fixture-model');
    assert.equal(await page.evaluate(() => window.shell.agentProviderStore.getSelectedProvider().models.includes('fixture-new-model')), false);
    assert.equal(JSON.parse(await fs.readFile(path.join(config, 'agent-provider-config.json'), 'utf8')).providers[0].models.includes('fixture-new-model'), false);
    await page.keyboard.press('Escape');
    await page.locator('#usGuard').waitFor({state:'visible'});
    await page.locator('[data-us-guard-cancel]').click();
    await page.locator('#agentSaveProviderBtn').click();
    await wait(async () => JSON.parse(await fs.readFile(path.join(config, 'agent-provider-config.json'), 'utf8')).providers[0].models.includes('fixture-new-model'), 'discovered models save');
    await page.unroute('**/api/agent/fetch-models');
    const failSave = async route => route.request().method() === 'POST'
        ? route.fulfill({ status: 503, contentType: 'application/json', body: '{"error":"fixture unavailable"}' })
        : route.continue();
    await page.route('**/api/agent-provider-config', failSave);
    await page.locator('#agentProviderNameInput').fill('不能保存的修改');
    const failedResponse = page.waitForResponse(response => response.url().endsWith('/api/agent-provider-config') && response.request().method() === 'POST');
    await page.locator('#agentSaveProviderBtn').click();
    await failedResponse;
    await wait(async () => await page.locator('#agentSaveProviderBtn').isEnabled(), 'failed save completion');
    assert.equal(await page.locator('#agentProviderNameInput').inputValue(), '不能保存的修改');
    assert.equal(await page.evaluate(() => window.shell.agentProviderStore.getSelectedProvider().label), '已修改的测试模型');
    await page.unroute('**/api/agent-provider-config', failSave);
    await page.keyboard.press('Escape');
    await page.locator('[data-us-discard]').click();
    await page.locator('#globalSettingsBtn').click();
    // Legacy shortcuts route to this same window.
    await page.evaluate(() => window.shell.openSettingsModal());
    assert.equal(await page.locator('#us-sharing').isVisible(), true);
    await page.evaluate(() => window.shell.openAgentConfigModal());
    assert.equal(await page.locator('#us-models').isVisible(), true);
    await page.locator('[data-us-tab=storage]').click();
    for (const width of [900, 680, 390]) {
        await page.setViewportSize({ width, height: 844 });
        assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, `overflow at ${width}`);
    }
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.locator('[data-us-mode=migrate]').click();
    await page.locator('#usTarget').fill(target);
    await page.locator('[data-us-plan]').click();
    await page.locator('#usPlan').waitFor({ state: 'visible' });
    assert.match(await page.locator('#usContents').innerText(), /个文件/);
    await page.locator('[data-us-change]').click();
    await wait(async () => JSON.parse(await fs.readFile(path.join(config, 'workspace.json'), 'utf8')).path === target, 'migration commit');
    await page.locator('.unified-settings').waitFor({ state: 'hidden' });
    await page.locator('#globalSettingsBtn').click();
    await page.locator('#usCurrentPath').filter({ hasText: target }).waitFor();
    assert.equal(await fs.readFile(path.join(target, 'src/pages/workspace-e2e/reader/docs/product.md'), 'utf8'), '# 产品文档\n迁移后保持可读');
    assert.match(await (await fetch(`${base}/src/pages/workspace-e2e/reader/v1/index.html`)).text(), /迁移验证/);
    assert.equal(await fs.readFile(path.join(app, 'portal/shell.js'), 'utf8'), originalShell, 'external workspace must not rewrite application fallback data');
    assert.equal(await fs.readFile(path.join(source, 'src/pages/workspace-e2e/reader/v1/annotations.json'), 'utf8'), '[{"text":"保留标注"}]');
    assert.equal(await fs.stat(path.join(target, 'data/agent-provider-config.json')).then(() => true, () => false), false);
    const history = await (await fetch(`http://127.0.0.1:${agentPort}/api/agent/sessions`)).json();
    assert.equal(history.sessions.some(session => session.id === 'retained-history'), true, 'history list survives workspace switch');
    assert.equal(JSON.parse(await fs.readFile(path.join(target, 'data/agent-sessions/retained-history.json'), 'utf8')).context.pageId, 'reader');
    const iterate = await fetch(`${base}/api/iterate`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ projectId: 'workspace-e2e', pageId: 'reader', sourceVersion: 'v1', newVersion: 'v2' }) });
    assert.equal(iterate.ok, true, await iterate.text());
    assert.match(await fs.readFile(path.join(target, 'src/pages/workspace-e2e/reader/v2/index.html'), 'utf8'), /迁移验证/);
    const snapshot = await fs.readFile(path.join(target, 'portal/shell.js'), 'utf8');
    const snapshotData = JSON.parse(snapshot.match(/const defaultData = ([\s\S]*?);\nif/)[1]);
    assert.deepEqual(snapshotData, JSON.parse(await fs.readFile(path.join(target, 'data/projects.json'), 'utf8')));
    const share = await fetch(`${base}/api/share-page`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ projectId: 'workspace-e2e', pageId: 'reader', version: 'v2', shareType: 'local' }) });
    assert.equal(share.ok, true, await share.clone().text());
    const shared = await share.json();
    assert.equal((await fetch(new URL(shared.url))).ok, true);
    // Two workspaces may reuse project/page IDs without sharing their contents.
    const second = path.join(temporary, 'second');
    await fs.cp(target, second, { recursive: true });
    await fs.writeFile(path.join(second, 'workspace.json'), JSON.stringify({ id: 'second-workspace', formatVersion: 1 }));
    await fs.writeFile(path.join(second, 'src/pages/workspace-e2e/reader/v1/index.html'), '<h1>另一个工作区</h1>');
    async function openWorkspace(location) {
        await page.locator('[data-us-mode=open]').click();
        await page.locator('#usTarget').fill(location);
        await page.locator('[data-us-plan]').click();
        await page.locator('#usPlan').waitFor({ state: 'visible' });
        await page.locator('[data-us-change]').click();
        await wait(async () => JSON.parse(await fs.readFile(path.join(config, 'workspace.json'), 'utf8')).path === location, 'workspace switch');
        await page.locator('.unified-settings').waitFor({ state: 'hidden' });
        await page.locator('#globalSettingsBtn').click();
        await page.locator('#usCurrentPath').filter({ hasText: location }).waitFor();
    }
    await openWorkspace(second);
    assert.match(await (await fetch(`${base}/src/pages/workspace-e2e/reader/v1/index.html`)).text(), /另一个工作区/);
    await openWorkspace(target);
    assert.match(await (await fetch(`${base}/src/pages/workspace-e2e/reader/v1/index.html`)).text(), /迁移验证/);
    const blank = path.join(temporary, 'blank');
    await page.locator('[data-us-mode=new]').click();
    await page.locator('#usTarget').fill(blank);
    await page.locator('[data-us-plan]').click();
    await page.locator('[data-us-change]').click();
    await wait(async () => JSON.parse(await fs.readFile(path.join(config, 'workspace.json'), 'utf8')).path === blank, 'blank workspace initialization');
    await page.locator('.unified-settings').waitFor({ state: 'hidden' });
    const create = await fetch(`${base}/api/create-project`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ projectId: 'new-project', projectName: '新工作区项目' }) });
    assert.equal(create.ok, true, await create.clone().text());
    assert.equal((await fs.stat(path.join(blank, 'src/pages/new-project'))).isDirectory(), true);
    await page.locator('#globalSettingsBtn').click();
    await openWorkspace(target);
    // An unavailable disk must offer recovery, never recreate assets in the app.
    await fs.rename(target, target + '-offline');
    await page.reload({ waitUntil: 'domcontentloaded' });
    await page.locator('#usAvailability').filter({ hasText: '不可用' }).waitFor();
    await openWorkspace(second);
    assert.match(await (await fetch(`${base}/src/pages/workspace-e2e/reader/v1/index.html`)).text(), /另一个工作区/);
    assert.equal(await fs.readFile(path.join(app, 'portal/shell.js'), 'utf8'), originalShell);
    assert.deepEqual(pageErrors, []);
    console.log('PASS: unified window, form persistence, shortcuts, responsive layout, migration, preview, iteration, local sharing, and unchanged application code.');
} finally {
    await browser?.close();
    await Promise.all(children.map(child => new Promise(resolve => { child.once('exit', resolve); child.kill('SIGTERM'); if (child.exitCode !== null) resolve(); })));
    await fs.rm(temporary, { recursive: true, force: true });
}
