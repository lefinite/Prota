import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import net from 'node:net';
import {spawn} from 'node:child_process';
import {chromium} from 'playwright';

const mod=process.platform==='darwin'?'Meta':'Control';
const app=process.cwd(), temp=await fs.mkdtemp(path.join(os.tmpdir(),'prota-text-clipboard-'));
const root=path.join(temp,'workspace'), dir=path.join(root,'src/pages/demo/design/v1');
const port=await new Promise(resolve=>{const s=net.createServer().listen(0,'127.0.0.1',()=>{const p=s.address().port;s.close(()=>resolve(p));});});
let child,browser,logs='';
try {
  await fs.mkdir(dir,{recursive:true});
  await fs.cp(path.join(app,'src/templates/infinite-canvas'),dir,{recursive:true});
  await fs.mkdir(path.join(root,'data'),{recursive:true});
  await fs.writeFile(path.join(root,'workspace.json'),JSON.stringify({id:'text-clipboard',formatVersion:1}));
  await fs.writeFile(path.join(root,'data/projects.json'),JSON.stringify({projects:[{id:'demo',name:'Demo',pages:[{id:'design',name:'Canvas',targetDevice:'canvas',pageMode:'infinite-canvas',versions:['v1']}]}],activeProjectId:'demo',activePageId:'design'}));
  child=spawn('python3',['server/bridge.py'],{cwd:app,env:{...process.env,READIFY_WORKSPACE:root,READIFY_CONFIG_DIR:path.join(temp,'config'),READIFY_PORT:String(port),PYTHONDONTWRITEBYTECODE:'1'},stdio:['ignore','pipe','pipe']});
  child.stdout.on('data',d=>logs+=d);child.stderr.on('data',d=>logs+=d);
  const base=`http://127.0.0.1:${port}`;
  let ready=false;for(let i=0;i<80;i++){try{if((await fetch(base+'/api/workspace')).ok){ready=true;break;}}catch{}await new Promise(r=>setTimeout(r,100));}
  assert.ok(ready,logs);
  browser=await chromium.launch({headless:true});
  const context=await browser.newContext({permissions:['clipboard-read','clipboard-write'],viewport:{width:1440,height:1000}});
  const page=await context.newPage();
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.route(base+'/clipboard-test',route=>route.fulfill({contentType:'text/html',body:'<iframe style="width:1400px;height:900px" src="/src/pages/demo/design/v1/index.html"></iframe>'}));
  await page.goto(base+'/clipboard-test');
  const frame=page.frames().find(f=>f.url().includes('/src/pages/'));
  await frame.waitForFunction(()=>window.protaCanvas);
  const state=()=>frame.evaluate(()=>window.protaCanvas.getState());
  await frame.locator('#stage').evaluate(el=>{
    const dataTransfer=new DataTransfer();dataTransfer.items.add(new File(['开始'],'document.md',{type:'text/markdown'}));
    el.dispatchEvent(new DragEvent('drop',{bubbles:true,dataTransfer,clientX:450,clientY:300}));
  });
  await frame.locator('.node.text').waitFor();await frame.locator('.node.text').dblclick();
  const input=frame.locator('.node.editing .node-content');
  const source=()=>input.evaluate(el=>CanvasMarkdownEditor.snapshot(el).source);
  const caret=async(start,end=start)=>input.evaluate((el,[a,b])=>CanvasMarkdownEditor.snapshot(el).select(a,b),[start,end]);
  await input.fill('- 父级');await caret(4);await page.keyboard.press('Enter');
  assert.equal(await source(),'- 父级\n- ');
  await page.keyboard.type('子级');await page.keyboard.press('Tab');
  assert.equal(await source(),'- 父级\n    - 子级');
  await page.keyboard.press('Enter');await page.keyboard.type('同级');
  assert.equal(await source(),'- 父级\n    - 子级\n    - 同级');
  await page.keyboard.press('Shift+Tab');
  assert.equal(await source(),'- 父级\n    - 子级\n- 同级');
  await page.keyboard.press(`${mod}+Z`);
  assert.equal(await source(),'- 父级\n    - 子级\n    - 同级','native undo preserves indentation');
  await input.fill('- 一级\n    - 二级\n        - 三级');await caret(7,26);
  const original=await source();await page.keyboard.press('Tab');await page.keyboard.press('Shift+Tab');
  assert.equal(await source(),original,'multiline indentation roundtrips');
  await input.fill('9. 条目');await caret(5);await page.keyboard.press('Enter');
  assert.equal(await source(),'9. 条目\n10. ');
  await page.keyboard.press('Enter');assert.equal(await source(),'9. 条目\n');
  await input.fill('- [x] 完成');await caret(8);await page.keyboard.press('Enter');
  assert.equal(await source(),'- [x] 完成\n- [ ] ');
  await input.fill('> 引用');await caret(4);await page.keyboard.press('Enter');
  assert.equal(await source(),'> 引用\n> ');
  await page.keyboard.press('Enter');assert.equal(await source(),'> 引用\n');
  await input.fill('```js\n- code');await caret(12);await page.keyboard.press('Enter');
  assert.equal(await source(),'```js\n- code\n','code does not continue lists');
  await input.fill('第一行');await caret(3);await page.keyboard.press('Enter');await page.keyboard.type('第二行');
  await frame.locator('[data-markdown-command="bold"]').click();
  assert.ok((await source()).includes('第二行**文字**'),'toolbar preserves source newlines');
  // Expanded editing uses exactly the same keyboard engine.
  await frame.getByRole('button',{name:'展开 Markdown 编辑器',exact:true}).click();
  const expanded=frame.getByRole('textbox',{name:'Markdown 源码',exact:true});
  await expanded.fill('- 项目');await expanded.press('End');await expanded.press('Tab');await expanded.press('Enter');
  assert.equal(await expanded.inputValue(),'    - 项目\n    - ');
  const md='# 标题\n\n第一行\n第二行\n\n- 一级\n    - 二级\n        1. 三级\n\n- [x] 完成\n\n| 名称 | 数值 |\n| --- | ---: |\n| **粗体** | 42 |\n\n> 引用\n\n```js\nconst a = 1;\n```\n\n~~删除~~ *斜体* [链接](https://example.com)';
  await expanded.fill(md);await frame.getByRole('button',{name:'保存',exact:true}).click();
  const id=(await state()).nodes.at(-1).id;
  const content=frame.locator(`.node[data-id="${id}"] .node-content`);
  assert.equal(await content.locator('p br').count(),1);
  assert.equal(await content.locator('ul ul ol li').count(),1);
  assert.equal(await content.locator('table tbody tr').count(),1);
  assert.equal(await content.locator('input:checked').count(),1);
  assert.equal(await content.locator('pre code').textContent(),'const a = 1;\n');
  assert.equal(await content.locator('del').textContent(),'删除');
  // Local Markdown file drops create the same editable text node and preview.
  await frame.locator('#stage').evaluate((el,md)=>{
    const transfer=new DataTransfer();transfer.items.add(new File([md],'import.md',{type:'text/markdown'}));
    el.dispatchEvent(new DragEvent('drop',{bubbles:true,cancelable:true,clientX:700,clientY:400,dataTransfer:transfer}));
  },md);
  await frame.waitForFunction(()=>protaCanvas.getState().nodes.some(n=>n.name==='import.md'));
  const imported=(await state()).nodes.find(n=>n.name==='import.md');
  assert.equal(imported.type,'text');assert.equal(imported.text,md);
  const importedEl=frame.locator(`.node[data-id="${imported.id}"] .node-content`);
  assert.equal(await importedEl.innerHTML(),await content.innerHTML(),'new and imported nodes render identically');
  await frame.evaluate(id=>protaCanvas.focus([id]),imported.id);
  await importedEl.dblclick();assert.equal(await source(),md);
  await input.fill('保留\n换行');
  await frame.getByRole('button',{name:'完成',exact:true}).click();
  await frame.evaluate(()=>protaCanvas.save());
  await frame.goto(frame.url());await frame.waitForFunction(()=>protaCanvas);
  assert.equal((await state()).nodes.find(n=>n.id===imported.id).text,'保留\n换行');
  // Mermaid reuses PRD rendering only; both canvas previews remain self-contained.
  await frame.locator(`.node[data-id="${imported.id}"]`).dblclick();
  const diagrams='```mermaid\nflowchart TD\nA[开始] --> B{确认}\nB --> C[完成]\n```\n\n```mermaid\nsequenceDiagram\nAlice->>Bob: 你好\nBob-->>Alice: 收到\n```';
  await input.fill(diagrams);
  await frame.getByRole('button',{name:'展开 Markdown 编辑器',exact:true}).click();
  await frame.locator('.markdown-editor-preview .canvas-mermaid[data-state=ready]').nth(1).waitFor();
  assert.equal(await frame.locator('.markdown-editor-preview .canvas-mermaid img').count(),2);
  await frame.getByRole('button',{name:'保存',exact:true}).click();
  await frame.locator(`.node[data-id="${imported.id}"] .canvas-mermaid[data-state=ready]`).nth(1).waitFor();
  assert.ok(await frame.locator(`.node[data-id="${imported.id}"] .canvas-mermaid img`).count()>=2);
  await frame.waitForFunction(id=>{const n=protaCanvas.getState().nodes.find(n=>n.id===id);const el=document.querySelector(`.node[data-id="${id}"] .node-content`);return Math.abs(n.height-el.scrollHeight)<=1;},imported.id);
  await frame.locator(`.node[data-id="${imported.id}"]`).dblclick();
  assert.equal(await source(),diagrams,'rendering keeps editable Mermaid source intact');
  await input.fill('```mermaid\nnot valid mermaid!!!\n```');
  await frame.getByRole('button',{name:'完成',exact:true}).click();
  const failed=frame.locator(`.node[data-id="${imported.id}"] .canvas-mermaid[data-state=error]`);
  await failed.waitFor();assert.equal(await failed.locator('pre').isVisible(),true);
  await frame.locator(`.node[data-id="${imported.id}"]`).dblclick();
  await input.fill(diagrams);await frame.getByRole('button',{name:'完成',exact:true}).click();
  await frame.locator(`.node[data-id="${imported.id}"] .canvas-mermaid[data-state=ready]`).nth(1).waitFor();
  await frame.evaluate(()=>protaCanvas.save());
  await frame.goto(frame.url());await frame.waitForFunction(()=>protaCanvas);
  await frame.locator(`.node[data-id="${imported.id}"] .canvas-mermaid[data-state=ready]`).nth(1).waitFor();
  assert.equal((await state()).nodes.find(n=>n.id===imported.id).text,diagrams);
  await page.screenshot({path:'/tmp/prota-canvas-mermaid.png'});
  assert.deepEqual(errors,[]);
  console.log('PASS: inline and expanded Markdown, nested list indentation, native undo, list/task/quote continuation, code fences, GFM rendering, local .md import parity, Mermaid flowchart/sequence rendering, error recovery and reload');

} finally {
  await browser?.close();child?.kill('SIGTERM');await fs.rm(temp,{recursive:true,force:true});
}
