import assert from 'node:assert/strict';
import { createServer } from 'node:http';
import { chromium } from 'playwright';
import { renderShareGate } from '../server/share_gate_page.mjs';
const server = createServer((req,res)=>{
    const state=new URL(req.url,'http://localhost').searchParams.get('state');
    const expired=state==='expired',wrong=req.method==='POST';
    res.setHeader('Content-Type','text/html; charset=utf-8');
    res.end(renderShareGate(expired?'此分享已过期，请联系分享者重新分享。':wrong?'密码不正确，请重试。':'此链接已启用密码保护。',!expired,expired?410:401));
});
await new Promise(done=>server.listen(0,'127.0.0.1',done));
const browser=await chromium.launch();
try {
    const page=await browser.newPage({viewport:{width:981,height:1031}});
    const errors=[];page.on('pageerror',error=>errors.push(error.message));
    const requests=[];page.on('request',request=>requests.push(request.url()));
    const origin=`http://127.0.0.1:${server.address().port}`;
    await page.goto(origin);
    assert.equal(await page.getByAltText('Prota',{exact:true}).isVisible(),true);
    assert.equal(await page.getByAltText('Prota 小狗守护分享').evaluate(image=>image.complete && image.naturalWidth>0),true);
    assert.equal(requests.length,1,'Brand and mascot must render before authentication, without separate asset requests');
    await page.getByLabel('访问密码',{exact:true}).fill('a4B9');
    await page.getByRole('button',{name:'显示密码'}).click();
    assert.equal(await page.locator('#password').getAttribute('type'),'text');
    await page.getByRole('button',{name:'隐藏密码'}).click();
    assert.equal(await page.locator('#password').getAttribute('type'),'password');
    await page.screenshot({path:'/tmp/prota-share-brand-locked.png'});
    await page.getByRole('button',{name:'查看分享',exact:true}).click();
    await page.getByRole('alert').waitFor();
    assert.equal(await page.locator('body').getAttribute('data-state'),'error');
    assert.equal(await page.locator('#password').inputValue(),'');
    assert.equal(await page.locator('#password').getAttribute('aria-invalid'),'true');
    assert.equal(await page.getByAltText('Prota 小狗提示密码错误').evaluate(image=>image.complete && image.naturalWidth>0),true);
    await page.screenshot({path:'/tmp/prota-share-brand-error.png'});
    await page.goto(origin+'/?state=expired');
    assert.equal(await page.getByRole('heading',{name:'这份分享已到期'}).isVisible(),true);
    assert.equal(await page.locator('form').count(),0);
    assert.equal(await page.getByAltText('Prota 小狗休息中').evaluate(image=>image.complete && image.naturalWidth>0),true);
    await page.screenshot({path:'/tmp/prota-share-brand-expired.png'});
    await page.setViewportSize({width:375,height:740});await page.goto(origin);
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
    assert.ok((await page.getByRole('button',{name:'查看分享',exact:true}).boundingBox()).y < 660);
    await page.screenshot({path:'/tmp/prota-share-brand-mobile.png'});
    await page.setViewportSize({width:375,height:420});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
    assert.deepEqual(errors,[]);
    const escaped=renderShareGate('<img src=x onerror=alert(1)>',false,404);
    assert.ok(escaped.includes('&lt;img src=x onerror=alert(1)&gt;'));
    console.log('Branded access page: logo/guardian without auth, password visibility, error/expired mascot, escaping and desktop/mobile layouts passed');
} finally {await browser.close();await new Promise(done=>server.close(done));}
