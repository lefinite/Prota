import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import net from 'node:net';
import { spawn } from 'node:child_process';
import { chromium } from 'playwright';

const app = process.cwd(), temporary = await fs.mkdtemp(path.join(os.tmpdir(), 'prota-board-browser-'));
const root = path.join(temporary, 'workspace'), pageRoot = path.join(root, 'src/pages/demo/design'), working = path.join(pageRoot, 'v1');
const port = await new Promise((resolve, reject) => { const s = net.createServer(); s.once('error', reject); s.listen(0, '127.0.0.1', () => { const port = s.address().port; s.close(() => resolve(port)); }); });
const base = `http://127.0.0.1:${port}`;
let child, browser, logs = '';
try {
  await fs.cp(path.join(app, 'src/templates/infinite-canvas'), working, { recursive: true });
  await fs.cp(path.join(app, 'tests/fixtures/canvas-v1'), working, { recursive: true });
  await fs.mkdir(path.join(root, 'data'), { recursive: true });
  await fs.writeFile(path.join(root, 'workspace.json'), JSON.stringify({ id: 'board-browser', formatVersion: 1 }));
  const config = path.join(root, 'data/canvas-features.json');
  await fs.writeFile(config, JSON.stringify({ testWorkspaceIds: ['board-browser'], overrides: { canvasSchemaV2: true, boardRevisions: true } }));
  await fs.writeFile(path.join(root, 'data/projects.json'), JSON.stringify({ projects: [{ id: 'demo', name: 'Demo', pages: [{ id: 'design', name: 'History', targetDevice: 'canvas', pageMode: 'infinite-canvas', versions: ['v1', 'v2'] }] }] }));
  child = spawn('python3', ['server/bridge.py'], { cwd: app, env: { ...process.env, READIFY_WORKSPACE: root, READIFY_CONFIG_DIR: path.join(temporary, 'config'), READIFY_PORT: String(port), PYTHONDONTWRITEBYTECODE: '1' }, stdio: ['ignore', 'pipe', 'pipe'] });
  child.stdout.on('data', data => logs += data); child.stderr.on('data', data => logs += data);
  let ready = false;
  for (let i = 0; i < 100; i++) { try { if ((await fetch(base + '/api/workspace')).ok) { ready = true; break; } } catch {} await new Promise(resolve => setTimeout(resolve, 100)); }
  assert.ok(ready, logs);
  browser = await chromium.launch({ headless: true });
  const tab = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = []; tab.on('pageerror', error => errors.push(error.message));
  await tab.goto(base + '/src/pages/demo/design/v1/index.html');
  await tab.waitForFunction(() => Boolean(window.protaCanvas)); await tab.evaluate(() => window.protaCanvasSchemaReady);
  await tab.locator('.node[data-id="home"] .node-title').click(); await tab.keyboard.press('ArrowRight');
  await tab.waitForFunction(() => !window.protaCanvas.isDirty() && window.protaCanvas.getState().revision === 8);
  const boardId = await tab.evaluate(() => window.protaCanvas.getState().nodes[0].boardId);
  const current = async (version = 'v1') => JSON.parse((await fs.readFile(path.join(pageRoot, version, 'canvas-data.js'), 'utf8')).slice('window.PROTA_CANVAS = '.length).trim().replace(/;$/, ''));
  const params = async (extra = {}) => { const baseline = await current(extra.version || 'v1'); return { projectId: 'demo', pageId: 'design', version: 'v1', nodeId: 'home', boardId, revision: baseline.revision, baseline, ...extra }; };
  const post = async (endpoint, data, status = 200) => { const response = await fetch(base + endpoint, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(data) }); const result = await response.json(); assert.equal(response.status, status, JSON.stringify(result)); return result; };
  await fs.mkdir(path.join(working, 'boards/home/modules'), { recursive: true });
  await fs.writeFile(path.join(working, 'boards/home/modules/answer.js'), 'export const answer = 42;');
  const originalEntry = await fs.readFile(path.join(working, 'boards/home/index.html'), 'utf8');
  await fs.writeFile(path.join(working, 'boards/home/index.html'), originalEntry.replace('<script src="app.js">', '<script type="module" src="app.js">'));
  const originalScript = await fs.readFile(path.join(working, 'boards/home/app.js'), 'utf8');
  await fs.writeFile(path.join(working, 'boards/home/app.js'), 'import {answer} from "./modules/answer.js"; document.body.dataset.answer = answer;\n' + originalScript);
  const first = await post('/api/boards/versions/create', await params({ label: 'Baseline' }));
  assert.equal((await current()).nodes[0].boardRevisionId, first.revisionId);
  // A stale open editor sees a real revision conflict, then keeps the existing recovery path.
  await tab.keyboard.press('ArrowRight');
  await tab.getByRole('button', { name: '读取最新版本', exact: true }).waitFor();
  assert.equal(await tab.evaluate(() => window.protaCanvas.isDirty()), true);
  await tab.getByRole('button', { name: '读取最新版本', exact: true }).click();
  await tab.waitForFunction(id => window.protaCanvas.getState().nodes[0].boardRevisionId === id && !window.protaCanvas.isDirty(), first.revisionId);
  const query = new URLSearchParams({ projectId: 'demo', pageId: 'design', boardId, revisionId: first.revisionId });
  const preview = await (await fetch(base + '/api/boards/versions/preview?' + query)).json();
  const historical = await browser.newPage();
  historical.on('console', message => { if (message.type() === 'error') console.error('History console:', message.text()); });
  historical.on('pageerror', error => console.error('History error:', error.message));
  historical.on('response', response => { if (response.status() >= 400) console.error('History resource:', response.status(), response.url()); });
  const response = await historical.goto(base + preview.url);
  assert.equal(response.headers()['content-security-policy'], 'sandbox allow-scripts allow-forms');
  await historical.waitForFunction(() => document.body.dataset.answer === '42');
  await historical.locator('#count').click(); assert.equal(await historical.locator('#count').textContent(), '1');
  assert.equal(await historical.evaluate(() => { try { return window.localStorage.length >= 0; } catch { return false; } }), false, 'historical HTML must not inherit Portal origin');
  const asset = await fetch(base + preview.url.replace('boards/home/index.html', 'assets/reference.svg')); assert.equal(asset.status, 200);
  assert.equal((await fetch(base + `/src/pages/demo/design/board-history/${boardId}/${first.revisionId}/files/boards/home/index.html`)).status, 404);
  await fs.symlink(path.join(pageRoot, 'board-history'), path.join(working, 'history-alias'));
  assert.equal((await fetch(base + `/src/pages/demo/design/v1/history-alias/${boardId}/${first.revisionId}/files/boards/home/index.html`)).status, 404);
  await fs.unlink(path.join(working, 'history-alias'));
  await fs.cp(working, path.join(pageRoot, 'v2'), { recursive: true });
  await fs.writeFile(path.join(working, 'boards/home/index.html'), '<!doctype html><h1>Second</h1><button>new work</button>');
  const second = await post('/api/boards/versions/create', await params());
  assert.equal(second.parentRevisionId, first.revisionId);
  const fork = await post('/api/boards/versions/create', await params({ version: 'v2', parentRevisionId: first.revisionId }));
  assert.equal(fork.parentRevisionId, first.revisionId);
  assert.equal((await current()).nodes[0].boardRevisionId, second.revisionId, 'v2 branch does not change v1');
  await fs.writeFile(path.join(working, 'boards/home/index.html'), '<!doctype html><h1>Uncommitted draft</h1>');
  const restored = await post('/api/boards/versions/restore', await params({ revisionId: first.revisionId }));
  assert.equal(restored.parentRevisionId, first.revisionId);
  assert.ok(restored.recoveryRevisionId);
  assert.ok((await fs.readFile(path.join(working, 'boards/home/index.html'), 'utf8')).includes('旧版首页'));
  assert.equal((await current('v2')).nodes[0].boardRevisionId, fork.revisionId);
  assert.ok((await fs.readFile(path.join(pageRoot, 'board-history', boardId, restored.recoveryRevisionId, 'files/boards/home/index.html'), 'utf8')).includes('Uncommitted draft'));
  const list = await (await fetch(base + '/api/boards/versions?' + query)).json();
  assert.equal(list.revisions.length, 5);
  await fs.writeFile(config, '{}');
  await post('/api/boards/versions/create', await params(), 403);
  assert.equal((await fetch(base + '/api/boards/versions?' + query)).status, 200);
  assert.deepEqual(errors, []);
  console.log('PASS: real board APIs, immutable sandbox preview/assets, 409 editor recovery, independent canvas branches, recovery snapshot, old-version restore and flag rollback');
} finally {
  await browser?.close();
  if (child && child.exitCode === null) { const exited = new Promise(resolve => child.once('exit', resolve)); child.kill(); await exited; }
  await fs.rm(temporary, { recursive: true, force: true });
}
