import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import net from 'node:net';
import {spawn} from 'node:child_process';
import {chromium} from 'playwright';

const mod=process.platform==='darwin'?'Meta':'Control';
const app=process.cwd(), temp=await fs.mkdtemp(path.join(os.tmpdir(),'prota-text-clipboard-'));
const root=path.join(temp,'workspace'), dir=path.join(root,'src/pages/demo/design/v1');
const port=await new Promise(resolve=>{const s=net.createServer().listen(0,'127.0.0.1',()=>{const p=s.address().port;s.close(()=>resolve(p));});});
let child,browser,logs='';
try {
  await fs.mkdir(dir,{recursive:true});
  await fs.cp(path.join(app,'src/templates/infinite-canvas'),dir,{recursive:true});
  await fs.mkdir(path.join(root,'data'),{recursive:true});
  await fs.writeFile(path.join(root,'workspace.json'),JSON.stringify({id:'text-clipboard',formatVersion:1}));
  await fs.writeFile(path.join(root,'data/projects.json'),JSON.stringify({projects:[{id:'demo',name:'Demo',pages:[{id:'design',name:'Canvas',targetDevice:'canvas',pageMode:'infinite-canvas',versions:['v1']}]}],activeProjectId:'demo',activePageId:'design'}));
  child=spawn('python3',['server/bridge.py'],{cwd:app,env:{...process.env,READIFY_WORKSPACE:root,READIFY_CONFIG_DIR:path.join(temp,'config'),READIFY_PORT:String(port),PYTHONDONTWRITEBYTECODE:'1'},stdio:['ignore','pipe','pipe']});
  child.stdout.on('data',d=>logs+=d);child.stderr.on('data',d=>logs+=d);
  const base=`http://127.0.0.1:${port}`;
  let ready=false;for(let i=0;i<80;i++){try{if((await fetch(base+'/api/workspace')).ok){ready=true;break;}}catch{}await new Promise(r=>setTimeout(r,100));}
  assert.ok(ready,logs);
  browser=await chromium.launch({headless:true});
  const context=await browser.newContext({permissions:['clipboard-read','clipboard-write'],viewport:{width:1440,height:1000}});
  const page=await context.newPage();
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.route(base+'/clipboard-test',route=>route.fulfill({contentType:'text/html',body:'<iframe style="width:1400px;height:900px" src="/src/pages/demo/design/v1/index.html"></iframe>'}));
  await page.goto(base+'/clipboard-test');
  const frame=page.frames().find(f=>f.url().includes('/src/pages/'));
  await frame.waitForFunction(()=>window.protaCanvas);
  const state=()=>frame.evaluate(()=>protaCanvas.getState());
  await frame.locator('#stage').dblclick({position:{x:450,y:300}});
  const input=frame.locator('.node.plain-text.editing textarea');
  await input.waitFor();assert.equal(await frame.locator('.markdown-inline-tools').count(),0);
  const end=()=>input.evaluate(el=>el.setSelectionRange(el.value.length,el.value.length));
  await input.fill('- 父级');await end();await input.press('Enter');
  assert.equal(await input.inputValue(),'- 父级\n- ');
  await input.pressSequentially('子级');await input.press('Tab');
  assert.equal(await input.inputValue(),'- 父级\n    - 子级');
  await input.press('Tab');assert.equal(await input.inputValue(),'- 父级\n        - 子级');
  await input.press('Shift+Tab');assert.equal(await input.inputValue(),'- 父级\n    - 子级');
  await input.press('Enter');await input.pressSequentially('同级');
  assert.equal(await input.inputValue(),'- 父级\n    - 子级\n    - 同级');
  await input.press('Shift+Tab');assert.equal(await input.inputValue(),'- 父级\n    - 子级\n- 同级');
  await input.press(`${mod}+Z`);assert.equal(await input.inputValue(),'- 父级\n    - 子级\n    - 同级');
  await end();await input.press('Enter');await input.press('Enter');
  assert.equal(await input.inputValue(),'- 父级\n    - 子级\n    - 同级\n- ');
  await input.press('Enter');assert.equal(await input.inputValue(),'- 父级\n    - 子级\n    - 同级\n');
  const block='- 一级\n    - 二级\n        - 三级';
  await input.fill(block);await input.evaluate(el=>el.select());
  await input.press('Tab');assert.equal(await input.inputValue(),'    - 一级\n        - 二级\n            - 三级');
  await input.press('Shift+Tab');assert.equal(await input.inputValue(),block);
  await input.fill('9. 条目');await end();await input.press('Enter');
  assert.equal(await input.inputValue(),'9. 条目\n10. ');
  await input.fill('- [x] 完成');await end();await input.press('Enter');
  assert.equal(await input.inputValue(),'- [x] 完成\n- [ ] ');
  await input.fill('```mermaid\n- code');await end();await input.press('Enter');
  assert.equal(await input.inputValue(),'```mermaid\n- code\n');
  await input.fill('- 仅换行');await end();await input.press('Shift+Enter');
  assert.equal(await input.inputValue(),'- 仅换行\n');
  assert.equal(await input.evaluate(el=>el===document.activeElement),true);
  assert.equal(await frame.locator('dialog,.markdown-inline-tools').count(),0);
  await input.fill('简洁文本\n第二行');
  // Real pointer clicks used to finish editing and steal focus into canvas gestures.
  await input.click();assert.equal(await input.evaluate(el=>el===document.activeElement),true);
  await input.press('End');await page.keyboard.type('，继续编辑');
  await input.dblclick();assert.equal(await input.evaluate(el=>el===document.activeElement),true);
  assert.equal(await frame.locator('.node.editing').count(),1);
  await input.fill('# 普通文本\n- 不转换为文档');
  await frame.locator('#stage').click({position:{x:1100,y:750}});
  const id=(await state()).nodes.at(-1).id;
  const content=frame.locator(`.node[data-id="${id}"] .node-content`);
  assert.equal(await content.locator('h1').textContent(),'普通文本');
  assert.equal(await content.locator('ul li').textContent(),'不转换为文档');
  await content.dblclick();await input.waitFor();await input.click();await input.press('End');
  await page.keyboard.type('，再次编辑');assert.ok((await input.inputValue()).endsWith('，再次编辑'));
  await input.fill('保存后再编辑');await frame.locator('#stage').click({position:{x:1100,y:750}});
  await frame.evaluate(()=>protaCanvas.save());await frame.goto(frame.url());await frame.waitForFunction(()=>protaCanvas);
  await frame.locator(`.node[data-id="${id}"] .node-content`).dblclick();await input.waitFor();
  assert.equal(await input.inputValue(),'保存后再编辑');assert.equal(await frame.locator('dialog,.markdown-inline-tools').count(),0);
  const mermaid='# 普通文本中的图表\n\n```mermaid\nflowchart LR\nA[开始] --> B[完成]\n```';
  await input.fill(mermaid);
  await frame.locator('#stage').click({position:{x:1100,y:750}});
  await content.locator('.canvas-mermaid[data-state=ready] img').waitFor();
  assert.equal(await content.locator('h1').textContent(),'普通文本中的图表');
  await content.dblclick();await input.waitFor();
  assert.equal(await input.inputValue(),mermaid);
  await input.click();assert.equal(await input.evaluate(el=>el===document.activeElement),true);
  assert.equal(await frame.locator('dialog,.markdown-inline-tools').count(),0);
  await frame.locator('#stage').click({position:{x:1100,y:750}});
  await frame.evaluate(()=>protaCanvas.save());await frame.goto(frame.url());await frame.waitForFunction(()=>protaCanvas);
  await content.locator('.canvas-mermaid[data-state=ready] img').waitFor();
  assert.deepEqual(errors,[]);
  console.log('PASS: inline list continuation, nested indent/outdent, multiline selection, undo, tasks, code fences, plain text double-click, actual pointer focus, repeated editing, Markdown and Mermaid rendering, no editing chrome, save and reload');

} finally {
  await browser?.close();child?.kill('SIGTERM');await fs.rm(temp,{recursive:true,force:true});
}
